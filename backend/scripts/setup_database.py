"""One-command database installer (works on Windows without the mysql CLI).

    python backend/scripts/setup_database.py            # asks before replacing an existing DB
    python backend/scripts/setup_database.py --yes      # non-interactive
    python backend/scripts/setup_database.py --no-sample-data

Steps (same order as described in README):
    01_schema -> 09_procedures_functions -> 10_triggers -> 08_views_indexes
    -> 13_security_privileges (app account, password from .env) -> 02_sample_data
Then copies the sample evidence files into storage/evidence so that
integrity verification works on the demo data.

Connects with DB_ADMIN_USER / DB_ADMIN_PASSWORD from .env.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

import pymysql  # noqa: E402

from app.config import get_settings  # noqa: E402
from app.utils.sql_script import split_sql  # noqa: E402

SQL_DIR = ROOT / "sql"
INSTALL_ORDER = [
    "01_schema.sql",
    "09_procedures_functions.sql",
    "10_triggers.sql",
    "08_views_indexes.sql",
    "13_security_privileges.sql",
]
SAMPLE = "02_sample_data.sql"


def _sql_quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "''")


def run_file(cur, path: Path, db_name: str, app_password: str) -> int:
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"\bghost_hunter\b", db_name, text)
    text = text.replace("CHANGE_ME_APP_PASSWORD", _sql_quote(app_password))
    count = 0
    for st in split_sql(text):
        cur.execute(st.sql)
        while True:
            if cur.description:
                cur.fetchall()
            if not cur.nextset():
                break
        count += 1
    return count


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--yes", action="store_true", help="replace an existing database without asking")
    ap.add_argument("--no-sample-data", action="store_true", help="install structure only")
    ap.add_argument("--database", help="database name (default: DB_NAME from .env)")
    args = ap.parse_args()

    s = get_settings()
    db_name = args.database or s.db_name
    if not re.fullmatch(r"[A-Za-z0-9_]{1,64}", db_name):
        print("Invalid database name"); return 2
    if not s.db_app_password or s.db_app_password.startswith("change"):
        print("Set DB_APP_PASSWORD in .env to a real password first."); return 2

    try:
        conn = pymysql.connect(host=s.db_host, port=s.db_port, user=s.db_admin_user,
                               password=s.db_admin_password, autocommit=True, charset="utf8mb4")
    except pymysql.MySQLError as exc:
        print(f"Could not connect to MySQL as {s.db_admin_user}@{s.db_host}:{s.db_port}: {exc}")
        return 1

    with conn.cursor() as cur:
        cur.execute("SELECT VERSION()")
        version = cur.fetchone()[0]
        print(f"Connected to MySQL {version}")
        if not version.startswith("8."):
            print("WARNING: MySQL 8.x is required (CHECK constraints, JSON, REGEXP_LIKE).")
        cur.execute("SELECT COUNT(*) FROM information_schema.schemata WHERE schema_name=%s", (db_name,))
        if cur.fetchone()[0] and not args.yes:
            ans = input(f"Database '{db_name}' exists and will be DROPPED and recreated. Continue? [y/N] ")
            if ans.strip().lower() != "y":
                print("Aborted."); return 1

        files = INSTALL_ORDER + ([] if args.no_sample_data else [SAMPLE])
        for name in files:
            n = run_file(cur, SQL_DIR / name, db_name, s.db_app_password)
            print(f"  ok  {name:32s} {n:4d} statements")

        cur.execute(f"SELECT COUNT(*) FROM `{db_name}`.audit_logs")
        audit_rows = cur.fetchone()[0]
    conn.close()

    if not args.no_sample_data:
        dest = Path(s.storage_dir) / "evidence"
        dest.mkdir(parents=True, exist_ok=True)
        copied = 0
        for f in sorted(Path(s.sample_evidence_dir).glob("ev*")):
            shutil.copyfile(f, dest / f.name)
            copied += 1
        print(f"  ok  copied {copied} sample evidence files to {dest}")
    print(f"Done. Database '{db_name}' ready ({audit_rows} audit records generated by triggers).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
